// Merchant webhook delivery — shared by every emitter that owes a
// merchant a notification about one of their transactions:
//
//   * transaction-webhook (provider inbound: MTN / Airtel / Zamtel /
//     generic) — the original caller;
//   * the mobile-money settlement observation points (developer-api,
//     momo-webhook, momo-requery) — a momo collection settles through
//     the rail requery path, never through transaction-webhook, so
//     without these call sites a merchant webhook could never fire
//     for a mobile-money payment (gate14, 2026-11-14).
//
// One implementation, deliberately free of Deno-specific APIs (only
// WebCrypto / fetch / AbortSignal, all present in Node ≥ 19 too) so
// the vitest suite can exercise the exact code the edge functions run.
//
// Delivery contract (the `webhooks` table — one row per merchant,
// written by update-webhook / the dashboard WebhookManager):
//   - The merchant-facing event vocabulary is what the dashboard
//     lets a merchant subscribe to: `payment_success` /
//     `payment_failed` (plus `settlement` / `refund`, which no
//     emitter produces yet). The notifier used to emit
//     `transaction.completed` / `transaction.failed` — names no
//     merchant could ever subscribe to through the UI — so a
//     dashboard-configured webhook could NEVER match and nothing was
//     ever delivered (gate14, 2026-11-14). The payload's `event` is
//     now the merchant-facing name; a row that literally subscribed
//     to `transaction.<status>` still matches (backward compatible)
//     and receives the literal name.
//   - Exactly-once per settlement: the delivery is claimed in
//     public.developer_event_dispatches on
//     `merchant_webhook:<event>:<transaction_id>` before sending —
//     the payment_link.paid pattern. Concurrent observers (API poll,
//     provider callback, requery poller) race on the claim; only the
//     first sends.
//   - Signed HMAC-SHA256 over the exact request body with the secret
//     on the webhook row itself (header X-Webhook-Signature:
//     sha256=<hex>). The secret is generated by the database default
//     and returned to the merchant by update-webhook on save.
//   - Best-effort: a dead endpoint is a logged "failed" result, never
//     an exception — the money path that triggered the notification
//     must never fail because a merchant URL is down.
//   - There is no merchant delivery-log table (unlike developer
//     webhooks); deliveries are console-logged only. Adding one is a
//     follow-up, not part of this fix.

import { assertSafeWebhookUrl } from "./url-guard.ts";

/** Transaction status → the merchant-facing event name. */
export const MERCHANT_EVENT_FOR_STATUS: Record<string, string> = {
  completed: "payment_success",
  failed: "payment_failed",
};

/** The event names a settlement of this status may be delivered as,
 *  in preference order: the merchant-facing name first, then the
 *  legacy literal name a row may have subscribed to directly. */
export function candidateMerchantEvents(status: string): string[] {
  const mapped = MERCHANT_EVENT_FOR_STATUS[status];
  const literal = `transaction.${status}`;
  return mapped ? [mapped, literal] : [literal];
}

/** Does a webhook row's `events` (text[] today; a boolean map on
 *  older rows) subscribe to any of the candidate names? Returns the
 *  name to deliver as, or null. */
// deno-lint-ignore no-explicit-any
export function matchedMerchantEvent(events: any, status: string): string | null {
  for (const name of candidateMerchantEvents(status)) {
    const subscribed = Array.isArray(events) ? events.includes(name) : !!events?.[name];
    if (subscribed) return name;
  }
  return null;
}

export async function merchantWebhookSignature(secret: string, body: string): Promise<string> {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    "raw",
    enc.encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const sig = await crypto.subtle.sign("HMAC", key, enc.encode(body));
  return "sha256=" + Array.from(new Uint8Array(sig)).map((b) => b.toString(16).padStart(2, "0")).join("");
}

export interface MerchantWebhookInput {
  /** The transaction owner's user id (the merchant). */
  userId: string;
  /** The id the merchant sees for this transaction: the platform
   *  transaction ref where one exists, else the ledger uuid. */
  transactionId: string;
  amount: number;
  currency: string;
  /** Ledger status: 'completed' | 'failed'. Anything else is a
   *  no-op — there is no merchant event for it. */
  status: string;
  externalReference?: string | null;
}

export interface MerchantWebhookResult {
  webhook_id: string;
  /** delivered | failed | skipped (unsafe URL) | already_notified */
  status: string;
  response_status: number | null;
}

/**
 * Notify the merchant's webhook endpoints about one settled (or
 * failed) transaction. Never throws. Returns one result per endpoint
 * considered; an empty array when there is nothing to notify (no
 * merchant, no matching subscription, unknown status, or an
 * already-claimed settlement).
 */
// deno-lint-ignore no-explicit-any
export async function notifyMerchantWebhooks(
  db: any,
  input: MerchantWebhookInput,
): Promise<MerchantWebhookResult[]> {
  try {
    const status = input.status;
    if (status !== "completed" && status !== "failed") return [];
    // The transaction belongs to a merchant account. Without a
    // merchant association we do NOT broadcast to unrelated
    // businesses.
    const { data: merchants } = await db.from("merchant_accounts")
      .select("id").eq("user_id", input.userId);
    const merchantIds = (merchants || []).map((m: any) => m.id);
    if (merchantIds.length === 0) {
      console.log("No merchant associated with transaction; skipping business webhook notifications", {
        transaction_id: input.transactionId,
      });
      return [];
    }
    const { data: owners } = await db.from("merchant_accounts")
      .select("user_id").in("id", merchantIds);
    const ownerIds = [...new Set((owners || []).map((o: any) => o.user_id).filter(Boolean))];
    if (ownerIds.length === 0) return [];

    // Exactly-once: claim this settlement before sending. A 23505
    // conflict means another observer already notified it.
    const { data: hooks } = await db.from("webhooks")
      .select("*").in("user_id", ownerIds);
    if (!hooks || hooks.length === 0) return [];
    const matched = hooks
      .map((hook: any) => ({ hook, event: matchedMerchantEvent(hook.events || [], status) }))
      .filter((m: any) => m.event !== null);
    if (matched.length === 0) return [];
    const eventName = matched[0].event as string;
    let claimed = true;
    const { error: claimError } = await db.from("developer_event_dispatches").insert({
      event_key: `merchant_webhook:${eventName}:${input.transactionId}`,
      user_id: input.userId,
    });
    if (claimError) {
      if ((claimError as { code?: string }).code === "23505") {
        claimed = false; // Already notified — a replay stays silent.
      } else {
        console.error("merchant webhook dispatch claim failed:", claimError.message ?? claimError);
      }
    }
    if (!claimed) {
      return matched.map((m: any) => ({
        webhook_id: m.hook.id, status: "already_notified", response_status: null,
      }));
    }

    const results: MerchantWebhookResult[] = [];
    for (const { hook, event } of matched) {
      const payload = {
        event,
        data: {
          transaction_id: input.transactionId,
          amount: input.amount,
          currency: input.currency,
          status,
          external_reference: input.externalReference ?? null,
          timestamp: new Date().toISOString(),
        },
      };
      try {
        assertSafeWebhookUrl(hook.url);
      } catch (e) {
        console.error("Blocked unsafe webhook URL:", hook.url, (e as Error).message);
        results.push({ webhook_id: hook.id, status: "skipped", response_status: null });
        continue;
      }
      const body = JSON.stringify(payload);
      // Sign with the secret on the webhook row itself: the live
      // column is `secret`, and there is no second lookup to get
      // wrong. A missing secret sends unsigned (an empty header),
      // exactly as the pre-shared version did — never fail the
      // notification for it.
      const signature = hook.secret ? await merchantWebhookSignature(hook.secret, body) : "";
      let deliveryStatus = "failed";
      let responseStatus: number | null = null;
      try {
        const res = await fetch(hook.url, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            "X-Webhook-Signature": signature,
          },
          body,
          signal: AbortSignal.timeout(10_000),
        });
        responseStatus = res.status;
        await res.text().catch(() => "");
        deliveryStatus = res.ok ? "delivered" : "failed";
        if (!res.ok) console.error("Merchant webhook delivery failed:", hook.url, res.status);
      } catch (e) {
        console.error("Failed to send webhook notification:", e instanceof Error ? e.message : e);
      }
      console.log("Webhook notification sent:", hook.url, deliveryStatus);
      results.push({ webhook_id: hook.id, status: deliveryStatus, response_status: responseStatus });
    }
    return results;
  } catch (e) {
    console.error("Error notifying business webhooks:", e instanceof Error ? e.message : e);
    return [];
  }
}

/**
 * Notify about a mobile-money settlement observed by any of the
 * requery paths (developer-api status poll, momo-webhook provider
 * callback, momo-requery poller). Loads the ledger row by its uuid
 * — the settle RPC's transaction id — and delegates. A missing row
 * (or a non-terminal status) is a silent no-op.
 */
// deno-lint-ignore no-explicit-any
export async function notifyMerchantMomoOutcome(
  db: any,
  args: { merchantUserId: string; transactionUuid: string; status: "completed" | "failed" },
): Promise<MerchantWebhookResult[]> {
  let row: any = null;
  try {
    const res = await db.from("transactions")
      .select("uuid_id, transaction_id, amount, currency, status, external_reference, user_id")
      .eq("uuid_id", args.transactionUuid)
      .maybeSingle();
    row = res?.data ?? null;
  } catch (e) {
    console.error("merchant momo notify: transaction lookup failed:", e instanceof Error ? e.message : e);
    return [];
  }
  if (!row) return [];
  return notifyMerchantWebhooks(db, {
    userId: row.user_id ?? args.merchantUserId,
    transactionId: row.transaction_id ?? row.uuid_id,
    amount: Number(row.amount),
    currency: row.currency,
    status: args.status,
    externalReference: row.external_reference ?? null,
  });
}
